/* campaign/site/map.js — the interactive atlas map (M4), the #atlas tab's landing view. Ported
   from the old campaign/atlas/index.html script: pan/zoom, clickable waypoints, a legend, a detail
   panel and a gazetteer, a label toggle. Its data (pins, legend, focus, gazetteer) comes from
   campaign/site/atlas-data.js (window.CaulAtlasData, generated by build_map.py) with each
   waypoint's link rerouted to its #atlas/<place> doc. Registers window.CaulMap(main), which
   site.js calls at #atlas. Everything is scoped to the host element and the one window listener
   removes itself once the host is gone, so a tab re-render leaves nothing behind. */
(function () {
  var SHELL =
    '<div class="atlas-shell">' +
    '  <div class="mapwrap" data-el="wrap">' +
    '    <div class="viewport" data-el="vp">' +
    '      <img data-el="img" src="campaign/atlas/umbra-map.jpeg" alt="Map of the world of Caul">' +
    '      <div data-el="markers"></div>' +
    '    </div>' +
    '    <div class="maplegend" data-el="legend"></div>' +
    '    <div class="zoomctl">' +
    '      <button data-el="zin" title="Zoom in">+</button>' +
    '      <button data-el="zout" title="Zoom out">−</button>' +
    '      <button data-el="zreset" title="Reset view" style="font-size:15px">↺</button>' +
    '    </div>' +
    '    <div class="maptoggle" data-el="labelToggle">Labels: Off</div>' +
    '    <div class="maphint">Scroll out for the whole world · drag to pan · click a waypoint</div>' +
    '  </div>' +
    '  <aside class="atlas-panel">' +
    '    <div class="atabs">' +
    '      <div class="atab active" data-tab="detail">Waypoint</div>' +
    '      <div class="atab" data-tab="gaz">Gazetteer</div>' +
    '    </div>' +
    '    <div class="apbody" data-el="apbody"></div>' +
    '  </aside>' +
    '</div>';

  window.CaulMap = function (main) {
    var DATA = window.CaulAtlasData || { pins: [], legend: [], gazetteer: [] };
    var host = document.createElement('div');
    host.className = 'caul-doc caul-tab atlas-host';
    host.innerHTML = SHELL;
    main.appendChild(host);
    var $ = function (n) { return host.querySelector('[data-el="' + n + '"]'); };

    var PINS = {}; DATA.pins.forEach(function (p) { PINS[p.name] = p; });
    var KL = {}; (DATA.legend || []).forEach(function (l) { KL[l.kind] = l.label; });
    var wrap = $('wrap'), vp = $('vp'), img = $('img'), apbody = $('apbody');
    var scale = 1, tx = 0, ty = 0, baseW = 1168, baseH = 0, activeName = null, tab = 'detail', labelsOn = false;

    function applyT() { vp.style.transform = 'translate(' + tx + 'px,' + ty + 'px) scale(' + scale + ')'; }
    function clamp() {
      var ww = wrap.clientWidth, wh = wrap.clientHeight, cw = baseW * scale, ch = baseH * scale;
      tx = cw <= ww ? (ww - cw) / 2 : Math.min(0, Math.max(ww - cw, tx));
      ty = ch <= wh ? (wh - ch) / 2 : Math.min(0, Math.max(wh - ch, ty));
    }
    function fit() { var ww = wrap.clientWidth, wh = wrap.clientHeight; scale = Math.min(ww / baseW, wh / baseH); tx = (ww - baseW * scale) / 2; ty = (wh - baseH * scale) / 2; applyT(); }
    function fitFocus() {
      var f = DATA.focus; if (!f) { fit(); return; }
      var ww = wrap.clientWidth, wh = wrap.clientHeight;
      var rx = f[0] / 100 * baseW, ry = f[1] / 100 * baseH, rw = (f[2] - f[0]) / 100 * baseW, rh = (f[3] - f[1]) / 100 * baseH;
      scale = Math.min(ww / rw, wh / rh) * 0.94; tx = ww / 2 - (rx + rw / 2) * scale; ty = wh / 2 - (ry + rh / 2) * scale; clamp(); applyT();
    }
    function zoomAt(cx, cy, f) { var ns = Math.min(6, Math.max(0.4, scale * f)), r = ns / scale; tx = cx - (cx - tx) * r; ty = cy - (cy - ty) * r; scale = ns; clamp(); applyT(); }
    function esc(s) { return (s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;'); }

    function buildMarkers() {
      var hostM = $('markers'); hostM.innerHTML = '';
      DATA.pins.forEach(function (p) {
        var px = p.xy[0], py = p.xy[1];
        var m = document.createElement('div');
        m.className = 'marker k-' + (p.kind || 'settlement');
        m.dataset.name = p.name;
        m.style.left = (px / 100 * baseW) + 'px'; m.style.top = (py / 100 * baseH) + 'px';
        m.innerHTML = '<div class="pin"></div><div class="mlabel">' + esc(p.name) + '</div>';
        m.addEventListener('click', function (ev) { ev.stopPropagation(); select(p.name); });
        hostM.appendChild(m);
      });
    }
    function buildLegend() { $('legend').innerHTML = (DATA.legend || []).map(function (l) { return '<div class="lg"><span class="sw k-' + l.kind + '"></span>' + esc(l.label) + '</div>'; }).join(''); }
    function focusMarker(name) {
      var p = PINS[name]; if (!p) return; var px = p.xy[0], py = p.xy[1];
      if (scale < 1.5) scale = 1.8; var wx = px / 100 * baseW * scale, wy = py / 100 * baseH * scale;
      tx = wrap.clientWidth / 2 - wx; ty = wrap.clientHeight * 0.46 - wy; clamp(); applyT();
    }
    function select(name) {
      activeName = name; tab = 'detail';
      host.querySelectorAll('.marker').forEach(function (m) { m.classList.toggle('active', m.dataset.name === name); });
      host.querySelectorAll('.atab').forEach(function (x) { x.classList.toggle('active', x.dataset.tab === 'detail'); });
      render(); focusMarker(name);
    }
    function render() {
      if (tab === 'gaz') {
        var h = '<p class="apintro">Every waypoint the company has walked. ◆ marks those set on the map — select one to find it.</p>';
        (DATA.gazetteer || []).forEach(function (g) {
          h += '<a class="gazrow" href="' + (g.url || '#atlas') + '" data-name="' + esc(g.name) + '" data-pinned="' + (g.pinned ? 1 : 0) + '">' +
               '<span class="gmark">' + (g.pinned ? '◆' : '') + '</span><span class="gnm">' + esc(g.name) + '</span><span class="gopen">entry ›</span></a>';
        });
        apbody.innerHTML = h;
        apbody.querySelectorAll('.gazrow').forEach(function (el) { el.onclick = function (ev) { if (el.dataset.pinned === '1') { ev.preventDefault(); select(el.dataset.name); } }; });
        apbody.scrollTop = 0; return;
      }
      if (!activeName) { apbody.innerHTML = '<div class="aempty"><span class="big">✶</span> Choose a waypoint on the map to read where it sits in the tale.<br><br>Or open the <b>Gazetteer</b> for every location.</div>'; return; }
      var p = PINS[activeName], role = KL[p.kind] || 'Waypoint';
      var link = p.url ? '<a class="dt-open" href="' + p.url + '">Open full entry ›</a>' : '<span class="dt-open dt-disabled">Not yet chronicled</span>';
      apbody.innerHTML = '<div class="dt-role">' + esc(role) + '</div><div class="dt-name">' + esc(p.name) + '</div><p class="dt-blurb">' + esc(p.blurb) + '</p>' + link;
      apbody.scrollTop = 0;
    }

    function ready() { baseH = baseW * (img.naturalHeight / img.naturalWidth); buildMarkers(); fitFocus(); }
    img.addEventListener('load', ready); if (img.complete && img.naturalWidth) ready();
    wrap.addEventListener('wheel', function (e) { e.preventDefault(); var r = wrap.getBoundingClientRect(); zoomAt(e.clientX - r.left, e.clientY - r.top, e.deltaY < 0 ? 1.18 : 1 / 1.18); }, { passive: false });
    var drag = false, sx, sy;
    wrap.addEventListener('pointerdown', function (e) { if (e.target.closest('.marker')) return; drag = true; sx = e.clientX; sy = e.clientY; wrap.classList.add('grabbing'); wrap.setPointerCapture(e.pointerId); });
    wrap.addEventListener('pointermove', function (e) { if (!drag) return; tx += e.clientX - sx; ty += e.clientY - sy; sx = e.clientX; sy = e.clientY; clamp(); applyT(); });
    wrap.addEventListener('pointerup', function () { drag = false; wrap.classList.remove('grabbing'); });
    $('zin').onclick = function () { zoomAt(wrap.clientWidth / 2, wrap.clientHeight / 2, 1.3); };
    $('zout').onclick = function () { zoomAt(wrap.clientWidth / 2, wrap.clientHeight / 2, 1 / 1.3); };
    $('zreset').onclick = fitFocus;
    $('labelToggle').onclick = function () { labelsOn = !labelsOn; $('markers').classList.toggle('labels-on', labelsOn); this.textContent = 'Labels: ' + (labelsOn ? 'On' : 'Off'); };
    host.querySelectorAll('.atab').forEach(function (t) { t.onclick = function () { tab = t.dataset.tab; host.querySelectorAll('.atab').forEach(function (x) { x.classList.toggle('active', x === t); }); render(); }; });

    // the one window listener; it removes itself once the tab has been re-rendered away
    function onResize() { if (!host.isConnected) { window.removeEventListener('resize', onResize); return; } clamp(); applyT(); }
    window.addEventListener('resize', onResize);

    buildLegend(); render();
  };
})();
